package zip.hedlund.pureedgesim.edgesdk.engine;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Locale;

import com.mechalikh.pureedgesim.distribution.Randomness;
import com.mechalikh.pureedgesim.scenariomanager.SimulationParameters;

import zip.hedlund.pureedgesim.edgesdk.api.Scenario;
import zip.hedlund.pureedgesim.edgesdk.model.Tier;

/**
 * Writes a run's settings into PureEdgeSim's static {@link SimulationParameters}
 * (which the core otherwise reads from its settings files), and seeds the core's
 * random stream with the run's workload seed.
 * <p>
 * PureEdgeSim copies its settings files next to its results, so the bridge also
 * writes small provenance files describing the SDK scenario and points the core
 * at them.
 */
public final class ParametersBridge {

	private ParametersBridge() {
	}

	public static void apply(RunSpec run) {
		Scenario s = run.scenario();
		var design = s.design();
		SimulationParameters.simulationDuration = s.duration();
		SimulationParameters.updateInterval = 1;
		SimulationParameters.networkUpdateInterval = s.networkUpdateInterval();
		SimulationParameters.simulationMapWidth = (int) Math.ceil(s.mapWidth());
		SimulationParameters.simulationMapLength = (int) Math.ceil(s.mapLength());
		SimulationParameters.numberOfCloudDataCenters = design.nodes(Tier.CLOUD).size();
		SimulationParameters.numberOfEdgeDataCenters = design.edgeNodes().size();
		int devices = design.nodes(Tier.END_DEVICE).size();
		SimulationParameters.minNumberOfEdgeDevices = devices;
		SimulationParameters.maxNumberOfEdgeDevices = devices;
		SimulationParameters.edgeDevicesIncrementationStepSize = 1;
		SimulationParameters.parallelism_enabled = false;
		SimulationParameters.pauseLength = 0;
		SimulationParameters.displayRealTimeCharts = false;
		SimulationParameters.autoCloseRealTimeCharts = true;
		SimulationParameters.chartsUpdateInterval = 1;
		SimulationParameters.saveCharts = false;
		SimulationParameters.deepLoggingEnabled = false;
		SimulationParameters.saveLog = false;
		SimulationParameters.cleanOutputFolder = false;
		SimulationParameters.realisticNetworkModel = true;
		SimulationParameters.enableOrchestrators = false;
		SimulationParameters.deployOrchestrators = "";
		SimulationParameters.orchestrationAlgorithms = new String[] { run.candidate().name() };
		SimulationParameters.orchestrationArchitectures = new String[] { "ALL" };
		SimulationParameters.enableRegistry = false;
		SimulationParameters.registryMode = "CLOUD";
		SimulationParameters.applicationList = new ArrayList<>();
		SimulationParameters.waitForAllTasksToFinish = false;
		SimulationParameters.edgeDevicesRange = 100;
		SimulationParameters.edgeDataCentersRange = 100;
		SimulationParameters.outputFolder = run.coreOutput().toString() + "/";
		writeProvenance(run);
		Randomness.setSeed(run.workloadSeed());
	}

	private static void writeProvenance(RunSpec run) {
		try {
			Path dir = run.coreOutput().resolve("sdk-settings");
			Files.createDirectories(dir);
			Path props = dir.resolve("simulation_parameters.properties");
			String text = String.format(Locale.ROOT,
					"# Generated by the Edge SDK; PureEdgeSim parameters are set in code.%n"
							+ "scenario=%s%nrun=%s%ncandidate=%s%ncondition=%s%nreplication=%d%n"
							+ "workload_seed=%d%nfault_seed=%d%nalgorithm_seed=%d%nduration=%s%n"
							+ "network_update_interval=%s%n",
					run.scenario().name(), run.runId(), run.candidate().name(), run.condition(), run.replication(),
					run.workloadSeed(), run.faultSeed(), run.algorithmSeed(), run.scenario().duration(),
					run.scenario().networkUpdateInterval());
			Files.writeString(props, text, StandardCharsets.UTF_8);
			String xml = "<?xml version=\"1.0\"?>\n<!-- Generated by the Edge SDK: the topology is declared in code ("
					+ run.scenario().name() + "). -->\n<sdk/>\n";
			for (String f : new String[] { "applications.xml", "edge_datacenters.xml", "edge_devices.xml",
					"cloud.xml" })
				Files.writeString(dir.resolve(f), xml, StandardCharsets.UTF_8);
			SimulationParameters.simulationParametersFile = props.toString();
			SimulationParameters.applicationFile = dir.resolve("applications.xml").toString();
			SimulationParameters.edgeDataCentersFile = dir.resolve("edge_datacenters.xml").toString();
			SimulationParameters.edgeDevicesFile = dir.resolve("edge_devices.xml").toString();
			SimulationParameters.cloudDataCentersFile = dir.resolve("cloud.xml").toString();
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}
}
